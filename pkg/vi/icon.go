func AddIcons(v ...Icon) {
	for _, icon := range v {
		icons = append(icons, Icon{
			key:  strings.ToLower(icon.key),
			code: icon.code,
		})
	}
}

func SVGIconByTitle(v string) string {
	initIconOnce.Do(func() {
		sort.Slice(icons, func(a, b int) bool {
			keyA := icons[a].key
			keyB := icons[b].key

			if len(keyA) == len(keyB) {
				return strings.Compare(keyA, keyB) < 0
			}
			return len(keyA) > len(keyB)
		})
	})

	v = strings.ToLower(v)
	if v == "x" {
		return TwitterSVG
	}
	for _, icon := range icons {
		if strings.Contains(v, icon.key) && v != "x" {
			return icon.code
		}
	}
	return TextSVG
}

